const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 let status=200, failRsvp=false;
 const future=new Date(Date.now()+86400000).toISOString();
 const past=new Date(Date.now()-86400000*5).toISOString();
 const appointment=(id,title,extra={})=>({id,title,startsAt:future,endsAt:null,location:'Sala de reunião',city:'Goiânia',role:'dono',myStatus:null,participants:[],ownerName:'Pessoa de teste',...extra});
 let appointments=[appointment('own','Reunião marcada'),appointment('invite','Convite pendente',{role:'convidado',myStatus:'pendente'}),appointment('old','Convite antigo pendente',{startsAt:past,role:'convidado',myStatus:'pendente'}),appointment('declined','Compromisso recusado',{role:'convidado',myStatus:'recusado'}),appointment('past','Compromisso encerrado',{startsAt:past})];
 await page.addInitScript(()=>localStorage.setItem('nexo:prefs:v1',JSON.stringify({completedAt:new Date().toISOString(),interests:['musica'],musicGenres:['rock'],homeWidgets:[{id:'trilha',tamanho:'metade'},{id:'agenda',tamanho:'inteira'}]})));
 await page.route('**/api/agenda/appointments',route=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(status===200?{appointments}:{error:'Teste'})}));
 await page.route('**/api/agenda/rsvp',async route=>{
  const body=route.request().postDataJSON();
  if(failRsvp) return route.fulfill({status:500,json:{error:'Falha simulada'}});
  appointments=appointments.map(a=>a.id===body.appointmentId?{...a,myStatus:body.status}:a);
  await route.fulfill({json:{ok:true}});
 });
 await page.goto(process.env.BASE_URL || 'http://localhost:3107');
 const agenda=page.locator('#agenda-home');
 await agenda.getByText('Reunião marcada',{exact:true}).waitFor();
 assert.equal(await agenda.count(),1);
 assert.equal(await page.locator('[data-widget="agenda"]').count(),0);
 assert.equal(await page.getByRole('link',{name:'Compromissos',exact:true}).count(),0);
 assert.ok(await page.getByRole('link',{name:'Agenda',exact:true}).count()>0);
 assert.equal(await agenda.getByText('Compromisso recusado',{exact:true}).count(),0);
 assert.equal(await agenda.getByText('Compromisso encerrado',{exact:true}).count(),0);
 await agenda.getByText('Convite antigo pendente',{exact:true}).waitFor();
 assert.equal(await agenda.evaluate(e=>e.previousElementSibling?.querySelector('h1')!==null && e.nextElementSibling?.id==='widgets'),true);
 const invite=agenda.getByRole('listitem').filter({hasText:'Convite pendente'});
 failRsvp=true;
 await invite.getByRole('button',{name:'Concordo',exact:true}).click();
 await agenda.getByText('Falha simulada',{exact:true}).waitFor();
 assert.equal(await invite.count(),1);
 failRsvp=false;
 await invite.getByRole('button',{name:'Concordo',exact:true}).click();
 await agenda.getByText('Você concordou com o compromisso.',{exact:true}).waitFor();
 await agenda.getByText('Confirmado',{exact:true}).waitFor();
 await agenda.getByRole('listitem').filter({hasText:'Convite antigo pendente'}).getByRole('button',{name:'Não concordo',exact:true}).click();
 await agenda.getByText('Você não concordou com o compromisso.',{exact:true}).waitFor();
 await page.screenshot({path:path.join(os.tmpdir(), 'nexo-social-home-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await agenda.scrollIntoViewIfNeeded();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(os.tmpdir(), 'nexo-social-home-mobile.png')});
 status=401;
 await page.reload();
 await agenda.getByText('Entre na sua conta',{exact:true}).waitFor();
 assert.equal(await agenda.getByText('Reunião marcada',{exact:true}).count(),0);
 status=500;
 await page.reload();
 await agenda.getByRole('button',{name:'Tentar novamente'}).waitFor();
 status=200;appointments=[];
 await agenda.getByRole('button',{name:'Tentar novamente'}).click();
 await agenda.getByText('Nenhum compromisso próximo.',{exact:false}).waitFor();
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: fixed placement, saved layout migration, sidebar label, upcoming dates, persistent pending invitations, RSVP success/failure, mobile overflow, anonymous/error/retry/empty states, no browser exceptions.');
})().catch(e=>{console.error(e);process.exit(1)});
